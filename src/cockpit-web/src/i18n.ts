export type TranslationKey = keyof typeof messages.en;
export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function normalizeLanguage(value: string | null | undefined): GuiLanguage {
  return value === "zh" ? "zh" : "en";
}

export function createTranslator(language: GuiLanguage): Translator {
  return (key, values) => interpolate(messages[language][key] ?? messages.en[key] ?? key, values);
}

export function translateKnownValue(t: Translator, value: string): string {
  const lookup: Record<string, TranslationKey> = {
    "New task": "view.newTask",
    "Not connected": "view.notConnected",
    "Awaiting task": "view.awaitingTask",
    "Ready for a new task": "view.readyNewTaskTitle",
    "Waiting for command": "view.waitingCommand",
    "API unavailable": "view.apiUnavailable",
    "Unavailable": "view.unavailable",
    "Live session": "view.liveSession",
    "Connected": "view.connected",
    "Disconnected": "view.disconnected",
    "Running": "view.running",
    "Fixture": "topbar.fixture",
    "Snapshot": "topbar.snapshot"
  };
  const key = lookup[value];
  return key ? t(key) : value;
}

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => values[key]?.toString() ?? match);
}
